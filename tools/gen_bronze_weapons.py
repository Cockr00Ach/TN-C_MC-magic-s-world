"""Build the shipped cuboid models, pixel textures, recipes and their offline preview.

Preview reads the emitted JSON geometry and PNG atlas, not the concept illustration.
Run from any directory: python tools/gen_bronze_weapons.py
"""
from pathlib import Path
import json,math,random
from PIL import Image,ImageDraw,ImageFont

ROOT=Path(__file__).resolve().parents[1]
RES=ROOT/'src/main/resources';ASSET=RES/'assets/tnc'
NAMES={'greatsword':'古铜大剑','spear':'古铜长枪','dao':'古铜大刀','dagger':'古铜匕首'}
PALETTE=[(83,78,57),(47,76,64),(130,119,89),(49,36,27),(98,77,50),(30,34,28),(100,102,74),(30,26,20)]

def write(path,value):
    path.parent.mkdir(parents=True,exist_ok=True);path.write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')

def atlas():
    image=Image.new('RGB',(128,64));rng=random.Random(20261103)
    for material,base in enumerate(PALETTE):
        for y in range(32):
            for x in range(32):
                noise=rng.randint(-13,13);color=base
                if material==0:
                    patch=math.sin(x*.35)+math.cos(y*.4)+math.sin((x+y)*.24)
                    if patch>.6:color=PALETTE[1]
                    if rng.random()<.08:color=PALETTE[5]
                if material==3:noise+=int(math.sin(x*2.7)*12)
                if material==4 and (x+y*2)%12<2:noise-=22
                image.putpixel(((material%4)*32+x,(material//4)*32+y),tuple(max(0,min(255,c+noise)) for c in color))
    out=ASSET/'textures/item/bronze_atlas.png';out.parent.mkdir(parents=True,exist_ok=True);image.save(out)

def build(kind):
    elements=[]
    def box(x0,y0,z0,x1,y1,z1,mat=0):
        # Continuous world-sized front UVs avoid repeating a whole patina tile on each thin blade row.
        u=max(0,min(3.8,(x0+4.2)*.44));v=(y0%16)*.5
        uv=[mat%4*4+u,mat//4*8+v,mat%4*4+min(4,u+max(.15,(x1-x0)*.44)),mat//4*8+min(8,v+max(.25,(y1-y0)*.5))]
        elements.append({'from':[round(x0+8,3),round(y0,3),round(z0+8,3)],'to':[round(x1+8,3),round(y1,3),round(z1+8,3)],'faces':{side:{'uv':uv,'texture':'#bronze'} for side in ('north','south','east','west','up','down')}})
    def rune(x,y,scale=1):
        # Cast squared spiral, legible from either side of the weapon.
        for z in (-1.02,.78):
            for a,b,c,d in [(0,0,1.6,.3),(1.3,0,1.6,2.2),(0,1.9,1.6,2.2),(0,.8,.3,2.2),(.1,.8,.9,1.1)]:
                box(x+a*scale,y+b*scale,z,x+c*scale,y+d*scale,z+.24,6)
    def grip(bottom,top,width=.65):
        box(-width,bottom,-width,width,top,width,3)
        for y in range(int(bottom)+1,int(top),2):box(-width-.08,y,-width-.08,width+.08,y+.45,width+.08,4)
        for y in (bottom,top-.5):box(-width-.25,y,-width-.25,width+.25,y+.5,width+.25,0)
    def beast(y,width):
        box(-width,y,-.95,width,y+1.9,.95,0)
        for side in (-1,1):
            x=side*(width-.7)
            box(x-.55,y+.6,-1.18,x+.55,y+1.4,-.96,6)
            box(x-.27,y+.75,-1.25,x+.27,y+1.16,-1.18,7)
        box(-.48,y-.7,-1.15,.48,y+1.2,-.95,0)
        box(-1,y-.65,-1.2,1,y-.25,-.95,6)
    if kind=='spear':
        grip(-14,16,.45)
        beast(14,1.9)
        box(-.48,15,-.48,.48,18,.48,0)
        for i in range(14):
            y=17+i;w=max(.25,2.6*(1-i/14))
            box(-w,y,-.55,w,y+1,.55,0)
            box(-w,y,-.38,-w+.23,y+1,.38,2);box(w-.23,y,-.38,w,y+1,.38,2)
        box(-.27,17,-.8,.27,30,.8,6)
        rune(-1.7,18,.65);rune(.7,18,.65)
        box(-.7,-15,-.7,.7,-13,.7,0)
    else:
        grip(-9 if kind!='dagger' else -3,2,.72 if kind!='dagger' else .55)
        beast(2,4.1 if kind=='greatsword' else 2.9)
        height=27 if kind=='greatsword' else 25 if kind=='dao' else 18
        for i in range(height):
            y=4+i
            if kind=='greatsword':left=-3.05;right=3.05;tip=max(.16,min(1,(height-i)/5));left*=tip;right*=tip
            elif kind=='dagger':w=max(.2,2.55*(1-i/height));left=-w;right=w
            else:
                left=-2.8+(i/height)*2.5;right=2.6+(i/height)*1.4
                if i>height-6:left+=(i-height+6)*.55
            if i in (4,11,17):left+=.22
            box(left,y,-.68,right,y+1,.68,0)
            box(left,y,-.4,left+.24,y+1,.4,2)
            if kind!='dao':box(right-.24,y,-.4,right,y+1,.4,2)
        if kind!='dao':box(-.25,4,-.9,.25,4+height-3,.9,6)
        for y in ([6,11,16] if kind!='dagger' else [5,8]):
            rune(0 if kind=='dao' else -1.3 if kind=='dagger' else -2.5,y,.4 if kind=='dagger' else .85)
            if kind=='greatsword':rune(.85,y,.85)
        if kind=='dao':
            for a,b,c,d in [(-1.25,-12,1.25,-11.5),(-1.25,-10,1.25,-9.5),(-1.25,-12,-.75,-9.5),(.75,-12,1.25,-9.5)]:box(a,b,-.5,c,d,.5,0)
        elif kind=='dagger':
            box(-1,-4,-.7,1,-2.8,.7,0);box(-1.7,-3.8,-.6,-.7,-3,.6,2);box(-.6,-3.5,-.9,-.2,-3.1,-.7,7)
        else:box(-1.2,-10.5,-.9,1.2,-8.8,.9,0)
    scale={'greatsword':.85,'spear':.9,'dao':.8,'dagger':.65}[kind]
    return {'credit':'TN-C ancient bronze weapons; generated by tools/gen_bronze_weapons.py',
        'textures':{'bronze':'tnc:item/bronze_atlas','particle':'tnc:item/bronze_atlas'},'gui_light':'front',
        'display':{
            'thirdperson_righthand':{'rotation':[0,-90,0],'translation':[0,2.5,1],'scale':[scale]*3},
            'thirdperson_lefthand':{'rotation':[0,90,0],'translation':[0,2.5,1],'scale':[scale]*3},
            'firstperson_righthand':{'rotation':[0,-90,15],'translation':[1,2,-2],'scale':[scale*.75]*3},
            'firstperson_lefthand':{'rotation':[0,90,-15],'translation':[1,2,-2],'scale':[scale*.75]*3},
            'gui':{'rotation':[0,0,-30],'translation':[0,-1,0],'scale':[.33 if kind=='spear' else .4]*3},
            'ground':{'rotation':[0,0,0],'translation':[0,3,0],'scale':[.25]*3},
            'fixed':{'rotation':[0,0,0],'translation':[0,0,0],'scale':[.4]*3}},'elements':elements}

def preview():
    # Render actual per-face atlas colors, with orthographic lighting and occlusion.
    tex=Image.open(ASSET/'textures/item/bronze_atlas.png').convert('RGB')
    canvas=Image.new('RGB',(1800,1180),(29,31,29));draw=ImageDraw.Draw(canvas)
    font=ImageFont.truetype('C:/Windows/Fonts/msyh.ttc',28);title=ImageFont.truetype('C:/Windows/Fonts/msyh.ttc',46)
    draw.text((75,35),'古铜兵器 · 成品模型预览',font=title,fill=(210,197,160))
    draw.text((78,101),'直接读取游戏模型与贴图离线渲染',font=font,fill=(142,152,134))
    sizes=[19,19,19,24]
    for index,kind in enumerate(NAMES):
        model=json.loads((ASSET/f'models/item/bronze_{kind}.json').read_text(encoding='utf-8'));faces=[]
        for el in model['elements']:
            x0,y0,z0=el['from'];x1,y1,z1=el['to']
            geometry={'north':[(x1,y0,z0),(x0,y0,z0),(x0,y1,z0),(x1,y1,z0)],
                'west':[(x0,y0,z0),(x0,y0,z1),(x0,y1,z1),(x0,y1,z0)],
                'up':[(x0,y1,z0),(x0,y1,z1),(x1,y1,z1),(x1,y1,z0)]}
            for side,points in geometry.items():
                depth=sum(p[2]+p[0]*.25-p[1]*.06 for p in points)/4
                faces.append((depth,side,points,el['faces'][side]['uv']))
        middle=(max(e['to'][1] for e in model['elements'])+min(e['from'][1] for e in model['elements']))/2
        zoom=sizes[index]
        def project(p):
            x,y,z=p;return (225+index*450+(x-8-(z-8)*.28)*zoom,620-(y-middle+(z-8)*.08)*zoom)
        for depth,side,pts,uv in sorted(faces,reverse=True):
            shade={'north':1.12,'west':.69,'up':1.28}[side]
            for j in range(12):
                for i in range(12):
                    def pt(u,v):return tuple(pts[0][k]*(1-u)*(1-v)+pts[1][k]*u*(1-v)+pts[2][k]*u*v+pts[3][k]*(1-u)*v for k in range(3))
                    u=(i+.5)/12;v=(j+.5)/12
                    tx=min(tex.width-1,int((uv[0]+(uv[2]-uv[0])*u)/16*tex.width));ty=min(tex.height-1,int((uv[1]+(uv[3]-uv[1])*v)/16*tex.height))
                    color=tuple(min(255,int(c*shade)) for c in tex.getpixel((tx,ty)))
                    draw.polygon([project(pt(i/12,j/12)),project(pt((i+1)/12,j/12)),project(pt((i+1)/12,(j+1)/12)),project(pt(i/12,(j+1)/12))],fill=color)
        draw.text((225+index*450,1090),NAMES[kind],font=title,anchor='mm',fill=(210,197,160))
    out=ROOT/'docs/previews/bronze_weapons_finished.png';out.parent.mkdir(parents=True,exist_ok=True);canvas.save(out);print(out)

def main():
    atlas()
    patterns={'greatsword':['CCC','CIC','LSL'],'spear':[' IC',' SC','SL '],'dao':[' CC',' IC',' SL'],'dagger':[' C ',' I ',' SL']}
    for kind in NAMES:
        write(ASSET/f'models/item/bronze_{kind}.json',build(kind))
        write(RES/f'data/tnc/recipes/bronze_{kind}.json',{'type':'minecraft:crafting_shaped','category':'equipment','pattern':patterns[kind],'key':{k:{'item':'minecraft:'+v} for k,v in {'C':'copper_ingot','I':'iron_ingot','S':'stick','L':'leather'}.items()},'result':{'item':f'tnc:bronze_{kind}'}})
        write(RES/f'data/tnc/advancements/recipes/bronze_{kind}.json',{'parent':'minecraft:recipes/root','criteria':{'copper':{'trigger':'minecraft:inventory_changed','conditions':{'items':[{'items':['minecraft:copper_ingot']}]}}},'rewards':{'recipes':[f'tnc:bronze_{kind}']}})
    write(RES/'data/tnc/recipes/bronze_upgrade.json',{'type':'tnc:bronze_upgrade','category':'equipment'})
    for lang in ('zh_cn','en_us'):
        path=ASSET/f'lang/{lang}.json';data=json.loads(path.read_text(encoding='utf-8-sig'))
        for kind,name in NAMES.items():data[f'item.tnc.bronze_{kind}']=name if lang=='zh_cn' else 'Ancient Bronze '+kind.title()
        keys={'bronze_upgrade':('铜铸强化：%s/10（基础攻击 +%s%%）','Copper tempering: %s/10 (+%s%% base damage)'),
            'bronze_combo':('战士连招：沿用 Q / E / Z、解锁与冷却规则','Warrior combos: existing Q / E / Z inputs, unlocks and cooldowns'),
            'bronze_throw':('按住右键蓄力，松开投掷；1.5 秒满蓄，自动回手','Hold use to charge; release to throw. Full charge: 1.5s. Returns automatically.'),
            'bronze_returning':('匕首回收中…','Dagger returning…')}
        for key,value in keys.items():data['tooltip.tnc.'+key]=value[0 if lang=='zh_cn' else 1]
        write(path,data)
    for tag,kinds in {'greatswords':['greatsword'],'spears':['spear'],'longswords':['dao','dagger'],'infusible_weapons':list(NAMES)}.items():
        path=RES/f'data/tnc/tags/items/{tag}.json';data=json.loads(path.read_text(encoding='utf-8')) if path.exists() else {'replace':False,'values':[]}
        for kind in kinds:
            value=f'tnc:bronze_{kind}'
            if value not in data['values']:data['values'].append(value)
        write(path,data)
    preview()

if __name__=='__main__':main()
