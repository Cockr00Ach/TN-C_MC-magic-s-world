import json, io

src = "src/main/resources/assets/tnc/models/projectile/fireball_core.json"
model = json.load(open(src, encoding="utf-8"))
els = model["elements"]

faces = []
for e in els:
    x1,y1,z1 = e["from"]
    x2,y2,z2 = e["to"]
    for d, f in e["faces"].items():
        u1,v1,u2,v2 = f["uv"]
        if d == "north":   corners = [(x1,y2,z1),(x1,y1,z1),(x2,y1,z1),(x2,y2,z1)]
        elif d == "south": corners = [(x2,y2,z2),(x2,y1,z2),(x1,y1,z2),(x1,y2,z2)]
        elif d == "west":  corners = [(x1,y2,z2),(x1,y1,z2),(x1,y1,z1),(x1,y2,z1)]
        elif d == "east":  corners = [(x2,y2,z1),(x2,y1,z1),(x2,y1,z2),(x2,y2,z2)]
        elif d == "up":    corners = [(x1,y2,z1),(x1,y2,z2),(x2,y2,z2),(x2,y2,z1)]
        else:              corners = [(x1,y1,z2),(x1,y1,z1),(x2,y1,z1),(x2,y1,z2)]
        uvs = [(u1,v1),(u1,v2),(u2,v2),(u2,v1)]
        row = []
        for (cx,cy,cz),(u,v) in zip(corners, uvs):
            row += [cx/16.0, cy/16.0, cz/16.0, u/16.0, v/16.0]
        faces.append(row)

lines = []
lines.append("package com.tnc.tnc.boss.fire.client;")
lines.append("")
lines.append("import com.mojang.blaze3d.vertex.PoseStack;")
lines.append("import com.mojang.blaze3d.vertex.VertexConsumer;")
lines.append("import net.minecraft.client.renderer.LightTexture;")
lines.append("import net.minecraft.client.renderer.MultiBufferSource;")
lines.append("import net.minecraft.client.renderer.RenderType;")
lines.append("import net.minecraft.client.renderer.texture.OverlayTexture;")
lines.append("import net.minecraft.resources.ResourceLocation;")
lines.append("")
lines.append("/**")
lines.append(" * Fireball core mesh baked straight from the author's bbmodel (14 boxes).")
lines.append(" * Generated by tools/gen_fireball_core_mesh.py - do not edit by hand.")
lines.append(" */")
lines.append("public final class FireballCoreMesh {")
lines.append("")
lines.append("    private static final ResourceLocation TEXTURE =")
lines.append("            ResourceLocation.fromNamespaceAndPath(\"tnc\", \"textures/block/fireball_core.png\");")
lines.append("    private static final RenderType TYPE = RenderType.entityCutoutNoCull(TEXTURE);")
lines.append("")
lines.append("    /** x, y, z, u, v per vertex; 4 vertices per quad. */")
lines.append("    private static final float[][] QUADS = {")
for row in faces:
    body = ", ".join("%.4fF" % v for v in row)
    lines.append("            {" + body + "},")
lines.append("    };")
lines.append("")
lines.append("    private FireballCoreMesh() {")
lines.append("    }")
lines.append("")
lines.append("    public static void render(PoseStack pose, MultiBufferSource buffer, float scale) {")
lines.append("        pose.pushPose();")
lines.append("        pose.scale(scale, scale, scale);")
lines.append("        pose.translate(-0.5F, -0.5F, -0.5F);")
lines.append("        VertexConsumer vc = buffer.getBuffer(TYPE);")
lines.append("        var mat = pose.last().pose();")
lines.append("        for (float[] q : QUADS) {")
lines.append("            for (int i = 0; i < 4; i++) {")
lines.append("                float x = q[i * 5];")
lines.append("                float y = q[i * 5 + 1];")
lines.append("                float z = q[i * 5 + 2];")
lines.append("                vc.vertex(mat, x, y, z)")
lines.append("                        .color(255, 255, 255, 255)")
lines.append("                        .uv(q[i * 5 + 3], q[i * 5 + 4])")
lines.append("                        .overlayCoords(OverlayTexture.NO_OVERLAY)")
lines.append("                        .uv2(LightTexture.FULL_BRIGHT)")
lines.append("                        .normal(0.0F, 1.0F, 0.0F)")
lines.append("                        .endVertex();")
lines.append("            }")
lines.append("        }")
lines.append("        pose.popPose();")
lines.append("    }")
lines.append("}")
io.open("src/main/java/com/tnc/tnc/boss/fire/client/FireballCoreMesh.java","w",encoding="utf-8",newline="\n").write("\n".join(lines)+"\n")
print("quads", len(faces))
