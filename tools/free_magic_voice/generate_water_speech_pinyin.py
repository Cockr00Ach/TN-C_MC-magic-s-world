"""Build the small Mandarin reading table used by WaterSpeech."""

import argparse
import hashlib
from pathlib import Path
import unicodedata
from urllib.request import urlopen

COMMIT = "fe29ad32bdf352b31a02b9936e537f575432e9a6"
SOURCE = f"https://raw.githubusercontent.com/mozillazg/pinyin-data/{COMMIT}"
PINYIN_HASH = "2342a6f98c85dbc3c8d26aef31744876a36326c6466e51e9a0f16898c36c2011"
LICENSE_HASH = "9c048697be2502a16e8bcb282d5d465a07295b2def0ffb05a269c5d39dbe1586"
RESOURCES = Path(__file__).resolve().parents[2] / "src/main/resources/data/tnc/free_magic"


def checked_source(name, expected_hash, local_path):
    if local_path is None:
        with urlopen(f"{SOURCE}/{name}", timeout=30) as response:
            data = response.read()
    else:
        data = local_path.read_bytes()
    if hashlib.sha256(data).hexdigest() != expected_hash:
        raise ValueError(f"Unexpected checksum for upstream {name}")
    return data


def dialect_key(reading):
    if reading.startswith(("zh", "ch", "sh")):
        reading = reading[0] + reading[2:]
    if reading.endswith(("ang", "eng", "ing")):
        reading = reading[:-1]
    return reading


def unaccent(reading):
    decomposed = unicodedata.normalize("NFD", reading).replace("u\u0308", "v")
    return "".join(char for char in decomposed if not unicodedata.combining(char))


def build_table(source):
    vocabulary = (RESOURCES / "water_speech_words.tsv").read_text(encoding="utf-8")
    defaults = {}
    for line in source.decode("utf-8").splitlines():
        if line.startswith("U+"):
            codepoint, readings = line.split(":", 1)
            char = chr(int(codepoint[2:], 16))
            defaults[char] = unaccent(readings.split("#", 1)[0].split(",", 1)[0].strip())
    families = set()
    for line in vocabulary.splitlines():
        if not line or line.startswith("#"):
            continue
        row = line.split("\t")
        sounds = row[1].split()
        for entry in row[2].split(",") if len(row) == 3 else ():
            spelling, _, override = entry.partition(":")
            sounds.extend(override.split() if override else (defaults[c] for c in spelling))
        families.update(map(dialect_key, sounds))
    rows = [
        "# Generated by tools/free_magic_voice/generate_water_speech_pinyin.py",
        f"# Data: https://github.com/mozillazg/pinyin-data/tree/{COMMIT} (MIT)",
        "# Default reading, with tone removed. See pinyin-data-LICENSE.txt.",
    ]
    for char, reading in defaults.items():
        if ord(char) <= 0xffff and dialect_key(reading) in families:
            rows.append(f"{char}\t{reading}")
    return ("\n".join(rows) + "\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pinyin", type=Path, help="Local copy of the pinned upstream pinyin.txt")
    parser.add_argument("--license", type=Path, help="Local copy of the pinned upstream LICENSE")
    parser.add_argument("--check", action="store_true", help="Verify generated files without writing")
    args = parser.parse_args()
    source = checked_source("pinyin.txt", PINYIN_HASH, args.pinyin)
    license_text = checked_source("LICENSE", LICENSE_HASH, args.license)
    outputs = {"water_speech_pinyin.tsv": build_table(source), "pinyin-data-LICENSE.txt": license_text}
    for name, data in outputs.items():
        path = RESOURCES / name
        if args.check:
            if path.read_bytes().replace(b"\r\n", b"\n") != data.replace(b"\r\n", b"\n"):
                raise SystemExit(f"{name} differs from pinned source")
        else:
            path.write_bytes(data)
        print(f"{name}: {len(data)} bytes")


if __name__ == "__main__":
    main()
