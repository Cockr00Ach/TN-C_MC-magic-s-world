"""法力护盾图标（16x16）：蓝色盾牌 + 中心亮核。"""

import pathlib

from PIL import Image

EDGE = (10, 32, 60)
BODY = (60, 168, 236)
LIGHT = (196, 240, 255)

# a=暗边 b=主体 c=高光
SHIELD = """
................
.....aaaaaa.....
....abbbbbba....
...abbbbbbbba...
...abbbccbbba...
...abbbccbbba...
...abbbbbbbba...
...abbbbbbbba...
....abbbbbba....
....abbbbbba....
.....abbbba.....
.....abbbba.....
......abba......
......aba.......
.......a........
................
"""

OUT = pathlib.Path('src/main/resources/assets/tnc/textures/spell/mana_shield.png')

img = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
for y, row in enumerate(SHIELD.strip('\n').split('\n')):
    for x, ch in enumerate(row):
        if ch == '.':
            continue
        r, g, b = {'a': EDGE, 'b': BODY, 'c': LIGHT}[ch]
        img.putpixel((x, y), (r, g, b, 255))
img.save(OUT)
print('wrote', OUT)
