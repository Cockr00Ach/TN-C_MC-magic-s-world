/**
 * @param {Internal.ItemStack} Output 
 * @param {string} spell_book 
 * @param {string} spell_id 
 */
function setNbt(Output, spell_book, spell_id) {
    let spell_ids = []
    spell_ids.push(spell_id)
    let Nbt = {
        spell_container: {
            pool: spell_bookMap[spell_book],
            spell_ids: spell_ids
        }
    }
    Output.setNbt(Nbt)
}


/**
 * @param {Internal.ListTag} ListTag 
 * @param {Internal.Tag} Tag 
 * @returns
 */
function findTag(ListTag, Tag) {
    let RE = false
    ListTag.forEach(Tags => {
        if (Tags == Tag) {
            RE = true
        }
    })
    return RE
}
